// TestShellInit_ZshHasBannerAndCompletion verifies the zsh snippet starts
// with the install banner and includes the cobra-generated completion body.
func TestShellInit_ZshHasBannerAndCompletion(t *testing.T) {
	bin := buildBinary(t)

	// Intentionally run with no working directory pinned to a git repo —
	// shell-init must work outside any git repo so users can stick the eval
	// in their rc file unconditionally.
	cmd := exec.Command(bin, "shell-init", "zsh")
	cmd.Dir = t.TempDir()
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("shell-init zsh failed: %v\n%s", err, out)
	}

	s := string(out)
	wantSubstrings := []string{
		"# idea(1) zsh completion",
		`echo 'eval "$(idea shell-init zsh)"' >> ~/.zshrc`,
		"intended for `eval`",
		"compinit",
		"compdef _idea idea",
		"_idea()",
	}
	for _, want := range wantSubstrings {
		if !strings.Contains(s, want) {
			t.Errorf("zsh output missing %q\n--- output ---\n%s", want, s)
		}
	}
}

