// TestShellInit_MissingShellExitsTwo verifies the no-arg error path.
func TestShellInit_MissingShellExitsTwo(t *testing.T) {
	bin := buildBinary(t)

	cmd := exec.Command(bin, "shell-init")
	cmd.Dir = t.TempDir()
	var stdout, stderr bytes.Buffer
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr
	err := cmd.Run()
	if err == nil {
		t.Fatalf("expected non-zero exit for missing shell arg")
	}
	exitErr, ok := err.(*exec.ExitError)
	if !ok {
		t.Fatalf("expected *exec.ExitError, got %T: %v", err, err)
	}
	if got := exitErr.ExitCode(); got != 2 {
		t.Errorf("expected exit code 2, got %d", got)
	}
	wantMsg := "idea shell-init: missing shell. Supported: zsh, bash"
	if !strings.Contains(stderr.String(), wantMsg) {
		t.Errorf("expected stderr to contain %q, got: %s", wantMsg, stderr.String())
	}
}

