// TestShellInit_CompletionSubcommandStillExists guards against accidentally
// removing or shadowing the cobra-autogenerated `completion` subcommand.
func TestShellInit_CompletionSubcommandStillExists(t *testing.T) {
	bin := buildBinary(t)

	cmd := exec.Command(bin, "completion", "zsh")
	cmd.Dir = t.TempDir()
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("completion zsh failed (it should still exist alongside shell-init): %v\n%s", err, out)
	}
	if !strings.Contains(string(out), "compdef _idea idea") {
		t.Errorf("expected legacy `completion zsh` to still emit cobra completion, got: %s", out)
	}
}
